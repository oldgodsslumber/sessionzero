// One-shot: .book/profiles.json -> profiles.js, the file that ships. Stats, labels, History
// and Personality; no art. Refuses to write while a doubt stands.
//
// usage: node tools/build-profiles.mjs <.book dir> <out file>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildVocab, cleanParagraph, suspects } from './prose.mjs';

const [, , bookDir, outFile] = process.argv;
const P = JSON.parse(fs.readFileSync(path.join(bookDir, 'profiles.json'), 'utf8'));

const vocab = buildVocab(path.join(bookDir, 'book.txt'), path.join(bookDir, 'words.txt'));
const here = path.dirname(fileURLToPath(import.meta.url));
const raw = JSON.parse(fs.readFileSync(path.join(here, 'prose-fixes.json'), 'utf8'));
const fixes = { keep: new Set(raw.keep), fixes: raw.fixes };
const splits = [], rare = new Map();
const prose = paras => paras.map(lines => cleanParagraph(lines, vocab, fixes, splits)).join('\n\n');

const doubted = P.filter(p => p.doubts.length);
if (doubted.length) {
  doubted.forEach(p => console.log(`p${p.page} ${p.name}: ${p.doubts.join('; ')}`));
  console.error(doubted.length + ' profiles still in doubt; nothing written');
  process.exit(1);
}

// What title case cannot work out.
const WORDS = {
  'S.H.I.E.L.D.': 'S.H.I.E.L.D.', 'A.I.M.': 'A.I.M.', 'M.O.D.O.K.': 'M.O.D.O.K.', "T'CHALLA": "T'Challa",
  'MCCOY': 'McCoy', "O'HARA": "O'Hara", 'JR.': 'Jr.', 'X': 'X', '2099': '2099', 'THE': 'the', 'GOD': 'God',
};
const NAME_FIX = {
  'MISTYKNIGHT': 'Misty Knight', 'A.I.M.AGENT': 'A.I.M. Agent', 'S.H.I.E.L.D.AGENT': 'S.H.I.E.L.D. Agent',
  'DOCTOR OCTOPUS (OTTO OCTAVIUS)E': 'Doctor Octopus (Otto Octavius)',
};
function titleName(raw) {
  const u = String(raw).toUpperCase().trim();
  if (NAME_FIX[u]) return NAME_FIX[u];
  return u.split(' ').map((w, i) => {
    const bare = w.replace(/^\(/, '').replace(/\)$/, '');
    const open = w.startsWith('(') ? '(' : '', close = w.endsWith(')') ? ')' : '';
    if (WORDS[bare] && (i > 0 || bare !== 'THE')) return open + WORDS[bare] + close;
    const t = bare.toLowerCase().replace(/(^|[-'.])([a-z])/g, (m, a, b) => a + b.toUpperCase());
    return open + t + close;
  }).join(' ');
}
const SET_WORDS = /[A-Za-z]+/g;
function titleSet(raw) {
  return String(raw).replace(/\*/g, '').replace(/ELEMENTAL CONTROLS/i, 'ELEMENTAL CONTROL').trim()
    .replace(SET_WORDS, w => w[0].toUpperCase() + w.slice(1).toLowerCase());
}
function tidy(s) {
  return String(s || '').replace(/(?<=[a-z])\.(?=[A-Z][a-z])/g, ', ').replace(/(?<=[A-Z]\.)(?=[A-Z][a-z])/g, ' ').replace('S.H.I.E.L.D. U.S.', 'S.H.I.E.L.D., U.S.').replace(/,(?=\S)/g, ', ').replace(/:(?=\S)/g, ': ')
    .replace(/\s+/g, ' ').trim() || null;
}
// OCR loses quote marks and the spaces round them: Matthew Matt"Murdock, Susan"Sue"Storm.
function tidyName(s) {
  const t = String(s || '').trim(), n = (t.match(/"/g) || []).length;
  if (n === 2) return t.replace(/\s*"\s*([^"]+?)\s*"\s*/, ' "$1" ').trim();
  if (n === 1) return t.replace(/(\S+?)\s*"\s*/, '"$1" ').trim();
  return t;
}
const spaced = s => String(s).replace(/\/\s+/g, '/').replace(/([a-z])\.(?=[A-Z][a-z])/g, '$1. ').replace(/,(?=[A-Za-z])/g, ', ');
const slug = n => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const rows = P.map(p => {
  const name = p.name.length && /^[A-Z]/.test(p.name) ? titleName(p.name) : p.name;
  const tags = p.tags.join('|');
  const kind = /(^|\|)Heroic/.test(tags) ? 'hero' : /(^|\|)Villainous/.test(tags) ? 'villain' : 'other';
  const row = {
    id: slug(name), name, page: p.page, kind, rank: p.rank, karma: p.karma == null ? 0 : p.karma,
    health: p.health, healthDR: p.healthDR, focus: p.focus, focusDR: p.focusDR,
    init: p.init, initEdge: p.initEdge, speeds: p.speeds,
    abilities: p.abilities, damage: p.damage,
    realName: tidyName(p.bio['Real Name']).replace(/\(a\.k\.a[.,]\s*/, '(a.k.a. '), origin: tidy(p.bio.Origin), occupation: tidy(p.bio.Occupation),
    size: tidy(p.bio.Size), teams: tidy(p.bio.Teams), base: tidy(p.bio.Base),
    history: prose(p.history), personality: prose(p.personality),
    traits: p.traits.map(spaced), tags: p.tags.map(spaced),
    powers: p.powers.map(x => ({ set: titleSet(x.set), name: spaced(x.name + (x.note ? (/^[(\[]/.test(x.note) ? ' ' : ': ') + x.note : '')) })),
  };
  if (p.formNote) row.formNote = p.formNote;
  Object.keys(row).forEach(k => { if (row[k] === null || row[k] === undefined) row[k] = ''; });
  return row;
});
rows.forEach(r => suspects(r.history + ' ' + r.personality, vocab).forEach(w => rare.set(w, r.page)));
const ids = new Set(rows.map(r => r.id));
if (ids.size !== rows.length) throw new Error('duplicate ids');

const body = rows.map(r => '  ' + JSON.stringify(r)).join(',\n');
const out = `// systems/marvel-multiverse/profiles.js — the Core Rulebook's character profiles (Chapter 8).
// GENERATED by tools/build-profiles.mjs. To correct a row, edit tools/profile-overrides.json.
//
// Numbers are as printed, including the book's own inconsistencies. Iron Man's Health is 75
// with Resilience 3, and the overrides file lists each one checked against the scan.
// page is the printed page number.
const MMR_PROFILES = [
${body},
];
`;
fs.writeFileSync(outFile, out);
console.log(rows.length, 'profiles written;', (out.length / 1024).toFixed(0) + ' KB');
console.log('words:', rows.reduce((n, r) => n + (r.history + ' ' + r.personality).split(/\s+/).length, 0));
console.log('split', splits.length, 'run-together words:', [...new Set(splits)].join('; '));
console.log('rare, to read:', [...rare].map(([w, p]) => w + ' (p' + p + ')').join('; '));
